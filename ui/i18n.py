def current_language():
    try:
        return st.session_state.get("lang", "en")
    except Exception:  # outside a Streamlit run (tests)
        return "en"


def is_rtl():
    return current_language() == "ar"


def t(key, **values):
    lang = current_language()
    text = TEXT.get(lang, {}).get(key) or TEXT["en"].get(key, key)
    return text.format(**values) if values else text


def cat(name):
    """Translate a category, subcategory or income-source name."""
    if not name:
        return ""
    if current_language() == "ar":
        return CATEGORY_NAMES_AR.get(name, name)
    return "Not specified" if name == "(unspecified)" else name


def money(value, signed=False):
    value = float(value or 0)
    sign = ("+" if value > 0 else "−" if value < 0 else "") if signed else ("−" if value < 0 else "")
    amount = f"{abs(value):,.0f}"
    unit = CURRENCY.get(current_language(), CURRENCY["en"])
    return f"{sign}{amount} {unit}"


def join(items):
    return ("، " if current_language() == "ar" else ", ").join(items)
